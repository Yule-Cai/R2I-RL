"""Generate a headless planner_server cfg for one map (paper matrix).

Same costmap/filter skeleton as the M3 campaign cfgs, but with a
configurable planner plugin list (probed availability). Prints the
plugin list used. Usage:
  python3 topopatch/tools/paper_planner_cfg.py --pgm <map.pgm> \\
      --plugins GridBased,Smac2D,ThetaStar --out planner_paper.yaml
Plugin ids map to Nav2 plugin classes; unknown ids raise (caller drops
them after probing ros2 pkg prefix).
"""
import argparse

CLASSES = {
    "GridBased": "nav2_navfn_planner::NavfnPlanner",
    "Smac2D": "nav2_smac_planner::SmacPlanner2D",
    "ThetaStar": "nav2_theta_star_planner::ThetaStarPlanner",
}

TEMPLATE = """# Generated by paper_planner_cfg.py (frozen deployment config).
map_server:
  ros__parameters:
    yaml_filename: "{pgm_yaml}"
    topic_name: "map"
    frame_id: "map"
planner_server:
  ros__parameters:
    expected_planner_frequency: 20.0
    planner_plugins: [{plugins}]
{blocks}
global_costmap:
  global_costmap:
    ros__parameters:
      global_frame: "map"
      robot_base_frame: "base_link"
      update_frequency: 10.0
      publish_frequency: 10.0
      resolution: 0.05
      track_unknown_space: true
      plugins: ["static_layer", "keepout_filter", "inflation_layer"]
      static_layer:
        plugin: "nav2_costmap_2d::StaticLayer"
        map_subscribe_transient_local: true
      keepout_filter:
        plugin: "nav2_costmap_2d::KeepoutFilter"
        enabled: true
        filter_info_topic: "keepout_costmap_filter_info"
      inflation_layer:
        plugin: "nav2_costmap_2d::InflationLayer"
        cost_scaling_factor: 3.0
        inflation_radius: 0.55
lifecycle_manager_navigation:
  ros__parameters:
    autostart: true
    node_names: ["map_server", "planner_server"]
"""

BLOCK = """    {pid}:
      plugin: "{cls}"
      tolerance: 0.5
      allow_unknown: true
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pgm-yaml", required=True)
    ap.add_argument("--plugins", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    pids = [p.strip() for p in a.plugins.split(",") if p.strip()]
    for p in pids:
        if p not in CLASSES:
            raise SystemExit(f"unknown planner id {p}")
    blocks = "".join(BLOCK.format(pid=p, cls=CLASSES[p]) for p in pids)
    open(a.out, "w").write(TEMPLATE.format(
        pgm_yaml=a.pgm_yaml,
        plugins=", ".join(f'"{p}"' for p in pids), blocks=blocks))
    print(f"[cfg] {a.out}: {pids}")


if __name__ == "__main__":
    main()
